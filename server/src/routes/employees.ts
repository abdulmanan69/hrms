const sipParams = z.object({ sipId: z.string().trim().min(1).max(20) });
const docParams = sipParams.extend({ docId: z.coerce.number().int().positive() });

const optNum = z.preprocess((v) => (v === '' || v === undefined ? undefined : v), z.coerce.number().int().positive().optional());
const optStr = z.preprocess((v) => (v === '' ? undefined : v), z.string().trim().max(100).optional());

const filterSchema = z.object({
  search: optStr,
  departmentId: optNum,
  designationId: optNum,
  status: z.enum(['pending', 'active', 'inactive', 'all']).default('all'),
  employmentStatus: z.preprocess((v) => (v === '' ? undefined : v), z.enum(EMPLOYMENT_STATUSES).optional()),
  managerSipId: optStr,
  sort: z.enum(['name', 'sipId', 'department', 'designation', 'dateOfJoining', 'status']).default('name'),
  dir: z.enum(['asc', 'desc']).default('asc'),
});
type Filters = z.infer<typeof filterSchema>;

const listSchema = paginationSchema.merge(filterSchema);

const readList = requirePermission('employees.view', 'team.view');
const manage = { preHandler: requirePermission('employees.manage') };
const docManage = { preHandler: requirePermission('documents.manage', 'employees.manage') };
const docRead = { preHandler: requirePermission('employees.view', 'documents.manage') };

function rejectImmutable(body: unknown): void {
  if (body && typeof body === 'object') {
    if ('sipId' in body) throw new ValidationError('The SIP ID is generated by the system and cannot be set or changed');
    if ('status' in body) throw new ValidationError('Use activate, deactivate or reactivate to change the status');
  }
}

/** WHERE for list, export and summary: caller scope plus filters. */
function listWhere(req: FastifyRequest, f: Partial<Filters>, withStatus = true): SQL | undefined {
  const sensitive = can(req.auth, 'employees.sensitive');
  let search: SQL | undefined;
  if (f.search) {
    const term = `%${f.search}%`;
    const digits = f.search.replace(/\D/g, '');
    const parts: Array<SQL | undefined> = [
      ilike(employees.sipId, term),
      ilike(employeeNameSql, term),
      ilike(employees.email, term),
      ilike(employees.phone, term),
      ilike(employees.altPhone, term),
    ];
    if (digits.length >= 4) {
      parts.push(sql`regexp_replace(coalesce(${employees.phone}, ''), '\\D', '', 'g') like ${`%${digits}%`}`);
    }
    // CNIC search only for people allowed to see CNICs, so it can't be used as an oracle.
    if (sensitive) {
      parts.push(ilike(employees.cnic, term));
      if (digits.length >= 4) parts.push(sql`regexp_replace(coalesce(${employees.cnic}, ''), '\\D', '', 'g') like ${`%${digits}%`}`);
    }
    search = or(...parts);
  }
  return and(
    scopeCondition(req.auth),
    withStatus && f.status && f.status !== 'all' ? eq(employees.status, f.status) : undefined,
    f.departmentId ? eq(employees.departmentId, f.departmentId) : undefined,
    f.designationId ? eq(employees.designationId, f.designationId) : undefined,
    f.employmentStatus ? eq(employees.employmentStatus, f.employmentStatus) : undefined,
    f.managerSipId ? eq(employees.managerSipId, f.managerSipId) : undefined,
    search,
  );
}

function orderOf(f: Filters): SQL[] {
  const d = f.dir === 'desc' ? desc : asc;
  switch (f.sort) {
    case 'sipId':
      return [d(employees.sipId)];
    case 'department':
      return [d(sql`coalesce(${departments.name}, 'zzz')`), asc(employees.firstName), asc(employees.lastName)];
    case 'designation':
      return [d(sql`coalesce(${designations.title}, 'zzz')`), asc(employees.firstName), asc(employees.lastName)];
    case 'dateOfJoining':
      return [d(employees.dateOfJoining), asc(employees.sipId)];
    case 'status':
      return [d(employees.status), asc(employees.firstName)];
    default:
      return [d(employees.firstName), d(employees.lastName), asc(employees.sipId)];
  }
}

const listColumns = {
  sipId: employees.sipId,
  firstName: employees.firstName,
  middleInitial: employees.middleInitial,
  lastName: employees.lastName,
  name: employeeNameSql,
  email: employees.email,
  phone: employees.phone,
  departmentId: employees.departmentId,
  departmentName: departments.name,
  designationId: employees.designationId,
  designationTitle: designations.title,
  managerSipId: employees.managerSipId,
  managerName: mgrNameSql,
  employmentStatus: employees.employmentStatus,
  status: employees.status,
  dateOfJoining: employees.dateOfJoining,
};


export async function employeeRoutes(app: FastifyInstance): Promise<void> {
  /* ---------------------------- self-service ---------------------------- */

  app.get('/me', async (req) => {
    const sipId = requireSelf(req);
    return employeeDetail(db, req.auth, sipId);
  });

  app.patch('/me', async (req) => {
    const sipId = requireSelf(req);
    const allowed = new Set(Object.keys(contactSchema.shape));
    const extra = Object.keys((req.body as object | null) ?? {}).filter((k) => !allowed.has(k));
    if (extra.length > 0) throw new ValidationError('You can change only your phone numbers, email and address. Ask HR to change anything else');
    const body = contactSchema.parse(req.body);
    await db.transaction(async (tx) => {
      const before = await loadEmployee(tx, sipId);
      const keys = changedKeys(before, body);
      if (keys.length === 0) return;
      const set: Record<string, unknown> = { updatedAt: new Date() };
      for (const k of keys) set[k] = body[k as keyof typeof body];
      const [after] = await tx.update(employees).set(set).where(eq(employees.sipId, sipId)).returning();
      await writeAudit(tx, req, {
        action: 'update_self',
        entity: 'employee',
        entityId: sipId,
        summary: `updated their own ${fieldList(keys)}`,
        before: pick(before, keys),
        after: pick(after, keys),
      });
    });
    return employeeDetail(db, req.auth, sipId);
  });

  /* ------------------------------ register ------------------------------ */

  app.get('/', { preHandler: readList }, async (req) => {
    const q = listSchema.parse(req.query);
    const where = listWhere(req, q);
    const [{ total }] = await db
      .select({ total: count() })
      .from(employees)
      .leftJoin(departments, eq(employees.departmentId, departments.id))
      .leftJoin(designations, eq(employees.designationId, designations.id))
      .where(where);
    const rows = await db
      .select(listColumns)
      .from(employees)
      .leftJoin(departments, eq(employees.departmentId, departments.id))
      .leftJoin(designations, eq(employees.designationId, designations.id))
      .leftJoin(mgr, eq(employees.managerSipId, mgr.sipId))
      .where(where)
      .orderBy(...orderOf(q))
      .limit(q.pageSize)
      .offset(offsetOf(q));
    return { data: rows, meta: pageMeta(q, total) };
  });

  /** Header counts. Status is not applied so the segmented filter keeps all counts. */
  app.get('/summary', { preHandler: readList }, async (req) => {
    const f = filterSchema.partial().parse(req.query);
    const where = listWhere(req, f, false);
    const byStatus = await db
      .select({ status: employees.status, n: count() })
      .from(employees)
      .where(where)
      .groupBy(employees.status);
    const n = (s: string) => byStatus.find((r) => r.status === s)?.n ?? 0;
    const byDepartment = await db
      .select({
        departmentId: employees.departmentId,
        departmentName: departments.name,
        active: sql<number>`count(*) filter (where ${employees.status} = 'active')::int`,
        pending: sql<number>`count(*) filter (where ${employees.status} = 'pending')::int`,
        total: sql<number>`count(*)::int`,
      })
      .from(employees)
      .leftJoin(departments, eq(employees.departmentId, departments.id))
      .where(where)
      .groupBy(employees.departmentId, departments.name)
      .orderBy(desc(sql`count(*)`));
    return {
      total: byStatus.reduce((a, r) => a + r.n, 0),
      active: n('active'),
      pending: n('pending'),
      inactive: n('inactive'),
      byDepartment,
    };
  });

  app.get('/export', { preHandler: readList }, async (req, reply) => {
    const f = filterSchema.parse(req.query);
    const sensitive = can(req.auth, 'employees.sensitive');
    const rows = await db
      .select({
      ...listColumns,
      altPhone: employees.altPhone,
      address1: employees.address1,
      address2: employees.address2,
      city: employees.city,
      state: employees.state,
      postalCode: employees.postalCode,
      country: employees.country,
      gender: employees.gender,
      cnic: employees.cnic,
      dateOfBirth: employees.dateOfBirth,
      bankName: employees.bankName,
      accountNo: employees.accountNo,
      deactivatedAt: employees.deactivatedAt,
    })
      .from(employees)
      .leftJoin(departments, eq(employees.departmentId, departments.id))
      .leftJoin(designations, eq(employees.designationId, designations.id))
      .leftJoin(mgr, eq(employees.managerSipId, mgr.sipId))
      .where(listWhere(req, f))
      .orderBy(...orderOf(f))
      .limit(20000);
    const headers = [
      'SIP ID',
      'Name',
      'First name',
      'Middle initial',
      'Last name',
      'Department',
      'Designation',
      'Manager SIP ID',
      'Manager',
      'Employment status',
      'Status',
      'Date of joining',
      'Deactivated on',
      'Email',
      'Phone',
      'Alternate phone',
      'Address',
      'Address line 2',
      'City',
      'State',
      'Postal code',
      'Country',
      'Gender',
      ...(sensitive ? ['CNIC', 'Date of birth', 'Bank', 'Account number'] : []),
    ];
    const body = rows.map((r) => [
      r.sipId,
      r.name,
      r.firstName,
      r.middleInitial,
      r.lastName,
      r.departmentName,
      r.designationTitle,
      r.managerSipId,
      r.managerName,
      r.employmentStatus,
      r.status,
      r.dateOfJoining,
      r.deactivatedAt ? r.deactivatedAt.toISOString().slice(0, 10) : null,
      r.email,
      r.phone,
      r.altPhone,
      r.address1,
      r.address2,
      r.city,
      r.state,
      r.postalCode,
      r.country,
      r.gender,
      ...(sensitive ? [r.cnic, r.dateOfBirth, r.bankName, r.accountNo] : []),
    ]);
    await writeAudit(db, req, {
      action: 'export',
      entity: 'employee',
      summary: `exported ${rows.length} employee ${rows.length === 1 ? 'record' : 'records'}`,
      after: { filters: f, rows: rows.length, sensitive },
    });
    return sendCsv(reply, `employees-${new Date().toISOString().slice(0, 10)}.csv`, toCsv(headers, body));
  });

  app.post('/', manage, async (req, reply) => {
    rejectImmutable(req.body);
    const body = createEmployeeSchema.parse(req.body);
    const emp = await db.transaction(async (tx) => {
      await checkReferences(tx, body);
      return createEmployee(tx, body, { userId: req.auth.userId, ip: req.ip });
    });
    return reply.status(201).send(await employeeDetail(db, req.auth, emp.sipId));
  });

  app.post('/bulk-status', manage, async (req) => {
    const body = z
      .object({
        sipIds: z.array(z.string().trim().min(1).max(20)).min(1, 'Pick at least one employee').max(200),
        action: z.enum(['activate', 'deactivate']),
        reason: z.string().trim().max(500).optional(),
      })
      .superRefine((b, ctx) => {
        if (b.action === 'deactivate' && !b.reason) ctx.addIssue({ code: 'custom', path: ['reason'], message: 'Give a reason for deactivating' });
      })
      .parse(req.body);
    const results: Array<{ sipId: string; name: string | null; ok: boolean; status: string | null; message: string }> = [];
    for (const sipId of [...new Set(body.sipIds)]) {
      try {
        const after = await db.transaction(async (tx) => {
          const cur = await loadEmployee(tx, sipId);
          const op = body.action === 'deactivate' ? 'deactivate' : cur.status === 'inactive' ? 'reactivate' : 'activate';
          return changeStatus(tx, req, sipId, op, body.reason ?? null);
        });
        results.push({
          sipId,
          name: fullName(after),
          ok: true,
          status: after.status,
          message: after.status === 'pending' ? 'Reactivated as pending: documents missing' : body.action === 'activate' ? 'Activated' : 'Deactivated',
        });
      } catch (err) {
        const [emp] = await db.select().from(employees).where(eq(employees.sipId, sipId));
        results.push({
          sipId,
          name: emp ? fullName(emp) : null,
          ok: false,
          status: emp?.status ?? null,
          message: err instanceof AppError ? err.message : 'Could not change this record',
        });
        if (!(err instanceof AppError)) req.log.error({ err, sipId }, 'bulk status failed');
      }
    }
    return { results, succeeded: results.filter((r) => r.ok).length, failed: results.filter((r) => !r.ok).length };
  });

  /* ------------------------- documents overview ------------------------- */

  /** Pending employees and what blocks each from going active. */
  app.get('/documents/blocked', docRead, async () => {
    const pending = await db
      .select({
        sipId: employees.sipId,
        name: employeeNameSql,
        departmentName: departments.name,
        designationTitle: designations.title,
        dateOfJoining: employees.dateOfJoining,
        createdAt: employees.createdAt,
      })
      .from(employees)
      .leftJoin(departments, eq(employees.departmentId, departments.id))
      .leftJoin(designations, eq(employees.designationId, designations.id))
      .where(eq(employees.status, 'pending'))
      .orderBy(asc(employees.dateOfJoining), asc(employees.sipId));
    const data = [];
    for (const p of pending) {
      const missing = await activationBlockers(db, p.sipId);
      const missingTypes = REQUIRED_DOCUMENTS.filter((t) => missing.includes(t === 'cnic' ? 'CNIC copy' : 'signed contract'));
      data.push({ ...p, missing, missingTypes, ready: missing.length === 0 });
    }
    return { data };
  });

  /** Every live document, newest first, with type / employee filters. */
  app.get('/documents', docRead, async (req) => {
    const q = paginationSchema
      .extend({
        type: z.preprocess((v) => (v === '' ? undefined : v), z.enum(DOCUMENT_TYPES).optional()),
        sipId: optStr,
        search: optStr,
      })
      .parse(req.query);
    const where = and(
      isNull(employeeDocuments.deletedAt),
      // CNIC scans only for those who may see CNICs
      maySeeCnicCopies(req.auth) ? undefined : ne(employeeDocuments.type, 'cnic'),
      q.type ? eq(employeeDocuments.type, q.type) : undefined,
      q.sipId ? eq(employeeDocuments.sipId, q.sipId) : undefined,
      q.search
        ? or(ilike(employees.sipId, `%${q.search}%`), ilike(employeeNameSql, `%${q.search}%`), ilike(employeeDocuments.fileName, `%${q.search}%`))
        : undefined,
    );
    const [{ total }] = await db
      .select({ total: count() })
      .from(employeeDocuments)
      .innerJoin(employees, eq(employeeDocuments.sipId, employees.sipId))
      .where(where);
    const rows = await db
      .select({
        id: employeeDocuments.id,
        sipId: employeeDocuments.sipId,
        employeeName: employeeNameSql,
        employeeStatus: employees.status,
        type: employeeDocuments.type,
        fileName: employeeDocuments.fileName,
        mimeType: employeeDocuments.mimeType,
        sizeBytes: employeeDocuments.sizeBytes,
        uploadedAt: employeeDocuments.uploadedAt,
        uploadedByName: users.name,
      })
      .from(employeeDocuments)
      .innerJoin(employees, eq(employeeDocuments.sipId, employees.sipId))
      .leftJoin(users, eq(employeeDocuments.uploadedBy, users.id))
      .where(where)
      .orderBy(desc(employeeDocuments.uploadedAt), desc(employeeDocuments.id))
      .limit(q.pageSize)
      .offset(offsetOf(q));
    return { data: rows, meta: pageMeta(q, total) };
  });

  /* ------------------------------- record ------------------------------- */

  app.get('/:sipId', async (req) => {
    const { sipId } = sipParams.parse(req.params);
    await assertCanReadEmployee(req.auth, sipId);
    return employeeDetail(db, req.auth, sipId);
  });

  app.patch('/:sipId', manage, async (req) => {
    const { sipId } = sipParams.parse(req.params);
    rejectImmutable(req.body);
    const body = updateEmployeeSchema.parse(req.body);
    await db.transaction(async (tx) => {
      const before = await loadEmployee(tx, sipId);
      // Without employees.sensitive the form never sees these values, so it must not overwrite them.
      if (!canSeeSensitive(req.auth, sipId)) {
        for (const k of ['cnic', 'bankName', 'accountNo', 'dateOfBirth'] as const) delete body[k];
      }
      if (body.cnic === null && before.cnic && before.status === 'active') {
        fieldError('cnic', 'An active employee must keep a CNIC number on record');
      }
      await checkReferences(tx, body, before);
      const keys = changedKeys(before, body);
      if (keys.length === 0) return;
      const set: Record<string, unknown> = { updatedAt: new Date() };
      for (const k of keys) set[k] = body[k];
      const [after] = await tx.update(employees).set(set).where(eq(employees.sipId, sipId)).returning();
      await writeAudit(tx, req, {
        action: 'update',
        entity: 'employee',
        entityId: sipId,
        summary: await updateSummary(tx, before, after, keys),
        before: pick(before, keys),
        after: pick(after, keys),
      });
    });
    return employeeDetail(db, req.auth, sipId);
  });

  app.post('/:sipId/activate', manage, async (req) => {
    const { sipId } = sipParams.parse(req.params);
    await db.transaction((tx) => changeStatus(tx, req, sipId, 'activate'));
    return employeeDetail(db, req.auth, sipId);
  });

  app.post('/:sipId/deactivate', manage, async (req) => {
    const { sipId } = sipParams.parse(req.params);
    const { reason } = z.object({ reason: z.string({ required_error: 'Give a reason for deactivating' }).trim().min(3, 'Give a reason for deactivating').max(500) }).parse(req.body ?? {});
    await db.transaction((tx) => changeStatus(tx, req, sipId, 'deactivate', reason));
    return employeeDetail(db, req.auth, sipId);
  });

  app.post('/:sipId/reactivate', manage, async (req) => {
    const { sipId } = sipParams.parse(req.params);
    const { reason } = z.object({ reason: z.string().trim().max(500).optional() }).parse(req.body ?? {});
    await db.transaction((tx) => changeStatus(tx, req, sipId, 'reactivate', reason ?? null));
    return employeeDetail(db, req.auth, sipId);
  });

  app.get('/:sipId/history', async (req) => {
    const { sipId } = sipParams.parse(req.params);
    await assertCanReadEmployee(req.auth, sipId);
    const q = paginationSchema.parse(req.query);
    const where = or(
      and(eq(auditTrail.entity, 'employee'), eq(auditTrail.entityId, sipId)),
      and(
        eq(auditTrail.entity, 'employee_document'),
        sql`${auditTrail.entityId} in (select ${employeeDocuments.id}::text from ${employeeDocuments} where ${employeeDocuments.sipId} = ${sipId})`,
      ),
    );
    const [{ total }] = await db.select({ total: count() }).from(auditTrail).where(where);
    const rows = await db
      .select({
        id: auditTrail.id,
        action: auditTrail.action,
        entity: auditTrail.entity,
        entityId: auditTrail.entityId,
        summary: auditTrail.summary,
        before: auditTrail.before,
        after: auditTrail.after,
        createdAt: auditTrail.createdAt,
        userId: auditTrail.userId,
        userName: users.name,
      })
      .from(auditTrail)
      .leftJoin(users, eq(auditTrail.userId, users.id))
      .where(where)
      .orderBy(desc(auditTrail.id))
      .limit(q.pageSize)
      .offset(offsetOf(q));
    const show = canSeeSensitive(req.auth, sipId);
    return {
      data: rows.map((r) => ({ ...r, before: redactAudit(r.before, show), after: redactAudit(r.after, show) })),
      meta: pageMeta(q, total),
    };
  });

  /* ------------------------------ documents ----------------------------- */

  app.get('/:sipId/documents', async (req) => {
    const { sipId } = sipParams.parse(req.params);
    await assertCanReadEmployee(req.auth, sipId);
    const emp = await loadEmployee(db, sipId);
    const data = (await documentRows(db, sipId)).filter((d) => d.type !== 'cnic' || maySeeCnicCopies(req.auth, sipId));
    return {
      data,
      required: REQUIRED_DOCUMENTS,
      blockers: emp.status === 'active' ? [] : await activationBlockers(db, sipId),
    };
  });

  app.post('/:sipId/documents', docManage, async (req, reply) => {
    const { sipId } = sipParams.parse(req.params);
    const file = await req.file();
    if (!file) throw new ValidationError('Attach a file');
    const field = file.fields.type;
    const raw = field && !Array.isArray(field) && field.type === 'field' ? String(field.value) : undefined;
    const type = z.enum(DOCUMENT_TYPES).safeParse(raw);
    if (!type.success) {
      file.file.resume();
      fieldError('type', 'Pick a document type: resume, cnic, offer_letter, contract or other');
    }
    const [emp] = await db.select().from(employees).where(eq(employees.sipId, sipId));
    if (!emp) {
      file.file.resume();
      throw new NotFoundError(`No employee with SIP ID ${sipId}`);
    }
    // file and record are written together: a failed insert leaves no orphan file
    const doc = await db.transaction(async (tx) => {
      const saved = await saveUpload(file, tx);
      const [row] = await tx
        .insert(employeeDocuments)
        .values({
          sipId,
          type: type.data,
          storedName: saved.storedName,
          fileName: saved.fileName,
          mimeType: saved.mimeType,
          sizeBytes: saved.sizeBytes,
          uploadedBy: req.auth.userId,
        })
        .returning();
      await writeAudit(tx, req, {
        action: 'upload',
        entity: 'employee_document',
        entityId: row.id,
        summary: `uploaded ${DOC_PHRASE[type.data]} for ${fullName(emp)}`,
        after: { sipId, type: row.type, fileName: row.fileName, sizeBytes: row.sizeBytes, uploadedSize: saved.originalSize, storedSize: saved.storedSize },
      });
      return row;
    });
    const { storedName: _s, deletedAt: _d, ...document } = doc;
    return reply.status(201).send({
      document,
      blockers: emp.status === 'active' ? [] : await activationBlockers(db, sipId),
    });
  });

  app.get('/:sipId/documents/:docId/download', async (req, reply) => {
    const { sipId, docId } = docParams.parse(req.params);
    const { download } = z.object({ download: z.enum(['1', 'true']).optional() }).parse(req.query);
    await assertCanReadEmployee(req.auth, sipId);
    const [doc] = await db
      .select()
      .from(employeeDocuments)
      .where(and(eq(employeeDocuments.id, docId), eq(employeeDocuments.sipId, sipId), isNull(employeeDocuments.deletedAt)));
    if (!doc) throw new NotFoundError('Document not found');
    if (doc.type === 'cnic' && !maySeeCnicCopies(req.auth, sipId)) throw new ForbiddenError('You cannot open CNIC copies');
    return sendUpload(reply, doc, !download);
  });

  app.delete('/:sipId/documents/:docId', docManage, async (req) => {
    const { sipId, docId } = docParams.parse(req.params);
    await db.transaction(async (tx) => {
      // lock the employee so two deletes can't both pass the 'not the only copy' check
      await tx.execute(sql`select 1 from employees where sip_id = ${sipId} for update`);
      const emp = await loadEmployee(tx, sipId);
      const [doc] = await tx
        .select()
        .from(employeeDocuments)
        .where(and(eq(employeeDocuments.id, docId), eq(employeeDocuments.sipId, sipId), isNull(employeeDocuments.deletedAt)));
      if (!doc) throw new NotFoundError('Document not found');
      if (emp.status === 'active' && REQUIRED_DOCUMENTS.includes(doc.type)) {
        const [{ n }] = await tx
          .select({ n: count() })
          .from(employeeDocuments)
          .where(and(eq(employeeDocuments.sipId, sipId), eq(employeeDocuments.type, doc.type), isNull(employeeDocuments.deletedAt)));
        if (n <= 1) {
          throw new ConflictError(`${fullName(emp)} is active and this is their only ${docName(doc.type)}. Upload a replacement first`);
        }
      }
      await tx.update(employeeDocuments).set({ deletedAt: new Date() }).where(eq(employeeDocuments.id, docId));
      await writeAudit(tx, req, {
        action: 'delete',
        entity: 'employee_document',
        entityId: docId,
        summary: `removed ${DOC_PHRASE[doc.type]} from the record of ${fullName(emp)}`,
        before: { sipId, type: doc.type, fileName: doc.fileName },
      });
    });
    return { ok: true, blockers: await activationBlockers(db, sipId) };
  });
}

/** CNIC scans: the employee themself, people who may see CNIC numbers, and HR document managers. */
function maySeeCnicCopies(auth: AuthContext, sipId?: string): boolean {
  return (!!sipId && auth.sipId === sipId) || can(auth, 'employees.sensitive') || can(auth, 'documents.manage') || can(auth, 'employees.manage');
}

function docName(t: DocumentType): string {
  return DOC_PHRASE[t].replace(/^an? /, '');
}

function pick<T extends object>(row: T, keys: readonly string[]): Record<string, unknown> {
  const out: Record<string, unknown> = {};
  for (const k of keys) out[k] = (row as Record<string, unknown>)[k];
  return out;
}
